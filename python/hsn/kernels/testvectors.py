"""The P2.9 test vectors on the Python side: load them (verified against ``MANIFEST.json`` and
:mod:`hsn.kernels.spec`) and run the P2.5 native ops on them.

The vectors live in ``kernels/testvectors/`` at the repository root, one safetensors file per
(size, op), ``<size>_<op>.safetensors``, generated by the Rust CPU oracle
(``rust/hsn-kernels/src/vectors.rs``; regenerate with ``HSN_WRITE_TESTVECTORS=1 cargo test -p
hsn-kernels --test oracle vectors_regenerate_deterministically``). Each holds every tensor of its op
under the header's argument names (:data:`hsn.kernels.spec.OPS`): forward inputs, forward outputs
including the saved ``hidden_saved`` / ``h_old_saved``, the cotangents that seed the backward,
and the gradients. Float tensors are f32 and exact in f16/bf16 where they are inputs; outputs and
gradients were computed in f64 and rounded once. ``MANIFEST.json`` pins every file by byte count
and SHA-256; :func:`load_vector` refuses a file that does not match it, a manifest of another spec
version, and any tensor whose name, dtype or shape is not the spec's (errors over silence).

:func:`run_native` is the adapter from a vector to the native ops of :mod:`hsn.kernels.native`,
through their public signatures only:

* ``gather_concat`` and ``gated_delta_update`` take the vector's tensors directly (indices widened
  to int64, ``valid`` to bool, ``age`` to int64 in a :class:`~hsn.model.state.CellGraphState`);
* ``grouped_unit_mlp`` runs a :class:`~hsn.model.units.UnitBank` (``activation="gelu"``, the
  exact erf GELU) holding the vector's ``W1``, ``b1``, ``W2``, ``b2``;
* ``csr_messages`` runs a :class:`~hsn.model.graph.CellGraph` with the vector's CSR
  (``set_topology``) and ``edge_norm="sigmoid"`` with ``edge_logit = logit(a)``, so that the
  native path computes with the vector's edge weights ``a`` (the op takes normalised weights;
  their normalisation is not part of it), and the edge-weight gradient is recovered as
  ``∂L/∂a = (∂L/∂logit) / (σ(logit)·(1 − σ(logit)))``. The logit and this recovery run in float64
  (on the host for MPS, which has no float64), so that they add no error of their own.

Gradients come from autograd seeded with the vector's cotangents. ``hidden_saved`` and
``h_old_saved`` are saved-for-backward tensors of the fused ABI with no native counterpart
(:data:`NATIVE_UNCOMPARED`); the Rust f32 oracle test checks them, and so will the kernels of
P2.10/P2.11. Module construction runs under :func:`torch.random.fork_rng`, so loading and running
a vector never advances the caller's random state.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path

import torch
from safetensors.torch import load as load_safetensors
from torch import Tensor, nn

from hsn.kernels import native, spec
from hsn.model.graph import CellGraph
from hsn.model.state import CellGraphState
from hsn.model.units import UnitBank

